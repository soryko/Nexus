#!/bin/bash
# Pre-launch verification for the A2 calibration, against the revision it is run at.
#
#   ./make-verification.sh [report.md]
#
# Writes a readable report AND a directory of untruncated logs beside it, then exits NONZERO
# if any check failed. The previous version used `set -uo pipefail` with no `-e` and no status
# accumulation, so its final `echo` decided the exit code: every check could fail and the
# generator still succeeded. It also filtered the output it printed while claiming to retain
# it verbatim -- so the filtered view is the REPORT now, and the verbatim text is the LOG.
set -uo pipefail
cd "$(dirname "$0")"

REPORT=${1:-PRELAUNCH-VERIFICATION.md}
LOGS=${LOGS:-verification-logs}
ARM=${ARM:-/Users/soko/Cerebros/nexus-a1-fixtures/calib-run/c30/run-k1/attempt1/arms/baseline}
rm -rf "$LOGS"; mkdir -p "$LOGS"
FAILED=0
declare -a RESULTS=()

# run <slug> <title> <command...>   -- full output to the log, status accumulated, never lost
run() {
  local slug=$1 title=$2; shift 2
  local log="$LOGS/$slug.log"
  "$@" > "$log" 2>&1
  local rc=$?
  [ $rc -ne 0 ] && FAILED=$((FAILED+1))
  RESULTS+=("$rc|$slug|$title")
  return 0
}

run counterexamples-calibration "Accounting and driver counterexamples" \
    python3 test_calibration_counterexamples.py
run counterexamples-detector    "Write-detector counterexamples" \
    python3 test_diagnose_counterexamples.py
run environment-gate            "Arm environment gate, against a prepared arm" \
    python3 verify_arm_environment.py "$ARM"
run isolation-heredoc           "Isolation: heredocs work, and are arm-private" \
    python3 assert_isolation.py "$ARM"
run product-suite               "Product suite" \
    ../../.venv-sqlite/bin/python -m pytest -q ../../tests

{
  echo "# Pre-launch verification — A2 calibration"
  echo
  if [ "$FAILED" -eq 0 ]; then
    echo "**All checks passed.** Generated by \`make-verification.sh\`, which exits nonzero if any"
    echo "check fails. Full untruncated output for every check is in \`$LOGS/\`; the excerpts below"
    echo "are excerpts, and the logs are the record."
  else
    echo "# ⚠ VERIFICATION FAILED — $FAILED check(s) did not pass"
    echo
    echo "**This report does not clear the launch gate.** Full output in \`$LOGS/\`."
  fi
  echo
  echo '```'
  echo "revision           $(git rev-parse HEAD)"
  echo "branch             $(git branch --show-current)"
  echo "date (UTC)         $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  echo "config version     $(python3 -c "import json;print(json.load(open('calib-config-30.json'))['config_version'])" 2>&1)"
  echo "schedule digest    $(python3 -c "import json;print(json.load(open('schedule-calib-a2.json'))['schedule_digest'][:16])" 2>&1)"
  echo "checks failed      $FAILED"
  echo '```'
  echo
  echo "| check | status | log |"
  echo "| --- | --- | --- |"
  for r in "${RESULTS[@]}"; do
    IFS='|' read -r rc slug title <<< "$r"
    [ "$rc" -eq 0 ] && st="PASS" || st="**FAIL (exit $rc)**"
    echo "| $title | $st | [\`$slug.log\`]($LOGS/$slug.log) |"
  done
  for r in "${RESULTS[@]}"; do
    IFS='|' read -r rc slug title <<< "$r"
    echo
    echo "## $title"
    echo '```'
    tail -20 "$LOGS/$slug.log"
    echo '```'
  done
} > "$REPORT"

echo "$REPORT written; $FAILED check(s) failed; full logs in $LOGS/" >&2
exit $(( FAILED > 0 ? 1 : 0 ))
